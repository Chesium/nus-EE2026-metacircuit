#!/usr/bin/env python3
"""Step one persistent RTL process and stop at its first settled-state divergence.

Golden compiles the canonical inputs/reference once; only settled checkpoints
invoke the accepted offline comparator. Replay uses a separate cold simulator.
"""
from __future__ import annotations

import argparse
import datetime
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tomllib

GOLDEN = Path(__file__).resolve().parents[1]
REPO = GOLDEN.parent


def read(path):
    return json.loads(Path(path).read_text())


def write(path, value):
    Path(path).write_text(json.dumps(value, indent=2) + '\n')


def command(argv, output, *, cwd=GOLDEN):
    with Path(output).open('w') as log:
        return subprocess.run(argv, cwd=cwd, stdout=log, stderr=subprocess.STDOUT).returncode


def prepare(scenario, output):
    """Use existing golden compilers, including measured input latency/line10."""
    source = output / 'scenario.json'
    write(source, scenario)
    npm = ['npm', 'run', 'golden', '--']
    for label, argv in (
        ('reference', npm + ['run', str(source), '--out', str(output / 'reference')]),
        ('canonical', npm + ['expand', str(source), '-o', str(output / 'canonical.json')]),
        ('stimulus', npm + ['stim', str(source), '-o', str(output / 'stim.toml')]),
    ):
        if command(argv, output / f'{label}.log'):
            raise RuntimeError(f'golden {label} compilation failed; see {output / (label + ".log")}')
    canonical, reference = read(output / 'canonical.json'), read(output / 'reference/checkpoints.json')
    if canonical['frameCount'] != reference['frameCount']:
        raise RuntimeError('canonical/reference frame counts differ')
    events = tomllib.loads((output / 'stim.toml').read_text()).get('event', [])
    by_frame = {}
    for event in events:
        if event.get('line') != 10 or not 0 <= event['frame'] < canonical['frameCount']:
            raise RuntimeError('compiled stimulus is outside the supported line10/frame range')
        if event['frame'] in by_frame:
            raise RuntimeError('duplicate canonical input frame')
        by_frame[event['frame']] = event['set']
    return canonical, reference, by_frame


def compare_checkpoint(actual, reference, checkpoint, completed, folder):
    """A one-checkpoint reference view keeps the accepted comparator unchanged."""
    folder.mkdir(parents=True)
    subset = folder / 'reference'
    subset.mkdir()
    for key in ('ram', 'state'):
        shutil.copy2(reference / checkpoint[key], subset / checkpoint[key])
    index = read(reference / 'checkpoints.json')
    write(subset / 'checkpoints.json', {**index, 'frameCount': completed, 'checkpoints': [checkpoint]})
    result = folder / 'state-compare.json'
    code = command(['npm', 'run', 'golden', '--', 'compare', str(actual), '--reference', str(subset),
                    '-o', str(result)], folder / 'comparison.log')
    if not result.exists():
        raise RuntimeError(f'accepted comparator produced no result (exit {code})')
    comparison = read(result)
    # Exit/result disagreement is infrastructure failure, not permission to pass.
    if code and comparison['ok']:
        raise RuntimeError(f'accepted comparator exited {code} despite passing evidence')
    return comparison


def collect_frame(response, frame, frames, stimulus):
    if response.get('completed_frames') != frame + 1:
        raise RuntimeError(f'session boundary is {response.get("completed_frames")}, expected {frame + 1}')
    found = [e for e in response.get('events', []) if e.get('event') == 'frame' and e.get('monitor') == 'vga']
    if len(found) != 1 or found[0]['index'] != frame:
        raise RuntimeError(f'missing/unexpected VGA frame event for frame {frame}')
    frames.append({**found[0], 'probes': response['probes']})
    for event in response.get('events', []):
        if event.get('event') == 'stim':
            expected = (event['frame'], event['line'], event['pixel'])
            actual = (event['at_frame'], event['at_line'], event['at_pixel'])
            stimulus.append({**event, 'late': expected != actual})


BOOT_STEP_MAX_TIME_MS = 1000


def replay_spec(framescope, config, output, seed, end, *, trace_frames=4, runtime="native", metacircuit=REPO):
    start = max(0, end - trace_frames + 1)
    argv = ['uv', 'run', 'framescope', '--runtime', runtime, 'run', '-c', str(config), '-s', str(output / 'stim.toml'),
            '-n', str(end + 1), '--seed', str(seed), '--save', 'none', '--dump', str(end),
            '--trace', f'{start}:{end - start + 1}', '-o', str(output / 'cold-replay')]
    return {'cwd': str(framescope), 'env': {'METACIRCUIT': str(metacircuit)}, 'argv': argv,
            'trace_from': start, 'trace_frames': end - start + 1,
            'note': 'Cold replay command; no FST generated by the persistent session.'}


def verify_cold_replay(output, divergence, initialization, compare=compare_checkpoint):
    """A successful simulator exit alone does not establish failure reproduction."""
    replay = output / 'cold-replay'
    report = read(replay / 'report.json')
    checkpoint = divergence['checkpoint']
    comparison = compare(replay, output / 'reference', checkpoint, divergence['frame'] + 1,
                         output / 'cold-replay-check')
    original = divergence['comparison']['checkpoints'][0]['differences']
    repeated = comparison['checkpoints'][0]['differences']
    index = read(output / 'reference/checkpoints.json')
    memories = {}
    for name in dict.fromkeys(index['names'].values()):
        relative = Path('dumps') / name / f'frame_{divergence["frame"]:04d}.json'
        before, after = read(output / 'rtl' / relative), read(replay / relative)
        memories[name] = all(before.get(k) == after.get(k)
                             for k in ('name', 'frame', 'width', 'depth', 'words'))
    same_initialization = report.get('sim', {}).get('initialization') == initialization
    return {'reproduced': bool(report.get('ok') and not comparison['ok'] and original == repeated
                              and same_initialization and memories and all(memories.values())),
            'comparison': comparison, 'same_initialization': same_initialization,
            'memory_word_equality': memories}


def lockstep(session, canonical, reference_index, by_frame, output, compare=compare_checkpoint):
    """Injectable loop, so early-stop behavior can be tested without another RTL build."""
    actual = output / 'rtl'
    actual.mkdir(exist_ok=True)
    report = {'ok': True, 'monitors': {'vga': {'frames': []}}, 'dumps': {}, 'stimulus': []}
    frames, stimulus = report['monitors']['vga']['frames'], report['stimulus']
    points = {}
    for checkpoint in reference_index['checkpoints']:
        if type(checkpoint.get('frame')) is not int or not 0 <= checkpoint['frame'] < canonical['frameCount']:
            raise RuntimeError('settled checkpoint is outside the canonical frame range')
        points.setdefault(checkpoint['frame'], []).append(checkpoint)
    if not points:
        raise RuntimeError('scenario has no settled checkpoints')
    results = []
    divergence = None
    with (output / 'requests.jsonl').open('w') as requests:
        def request(value):
            requests.write(json.dumps(value) + '\n')
            requests.flush()
            answer = session.request(value)
            if not answer.get('ok'):
                raise RuntimeError(f'session {value["op"]} failed: {answer.get("error", answer)}')
            return answer

        for frame in range(canonical['frameCount']):
            values = by_frame.get(frame)
            if values:
                request({'op': 'poke', 'values': values, 'line': 10, 'pixel': 0, 'id': f'input-{frame}'})
            step = {'op': 'step', 'frames': 1, 'id': f'frame-{frame}'}
            if frame == 0:
                # Seeded cold boot reaches its first frame boundary at 86-124 ms (seed/Verilator
                # dependent), past the session's default 3-frame allowance; later frames keep it.
                step['max_time_ms'] = BOOT_STEP_MAX_TIME_MS
            answer = request(step)
            collect_frame(answer, frame, frames, stimulus)
            write(actual / 'report.json', report)
            if frame not in points:
                continue
            for name in dict.fromkeys(reference_index['names'].values()):
                answer = request({'op': 'memory', 'name': name, 'id': f'memory-{frame}-{name}'})
                memory = answer['memory']
                if memory['frame'] != frame or memory['name'] != name:
                    raise RuntimeError(f'{name}: memory boundary/name differs from completed frame {frame}')
                path = actual / 'dumps' / name / f'frame_{frame:04d}.json'
                path.parent.mkdir(parents=True, exist_ok=True)
                write(path, memory)
                report['dumps'].setdefault(name, []).append({'frame': frame, 'path': str(path)})
            write(actual / 'report.json', report)
            for i, checkpoint in enumerate(points[frame]):
                comparison = compare(actual, output / 'reference', checkpoint, frame + 1,
                                     output / 'checks' / f'frame-{frame:04d}-{i}')
                results.append(comparison)
                if not comparison['ok']:
                    divergence = {'frame': frame, 'checkpoint': checkpoint,
                                  'comparison': comparison, 'inputs': str(output / 'canonical.json'),
                                  'trace_window': frames[max(0, len(frames) - 4):]}
                    write(output / 'first-divergence.json', divergence)
                    break
            if divergence:
                break
    return {'ok': divergence is None, 'frames_completed': len(frames), 'comparisons': results,
            'first_divergence': divergence}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument('--case', type=Path, help='saved seeded M4 stress/reduced case')
    source.add_argument('--scenario', type=Path, help='ordinary golden scenario (requires --seed)')
    parser.add_argument('--seed', type=int)
    parser.add_argument('--framescope', type=Path, default=REPO.parent / 'framescope')
    parser.add_argument('--runtime', choices=['native', 'docker'], default='native')
    parser.add_argument('--out', type=Path)
    parser.add_argument('--replay-failure', action='store_true', help='run the saved cold FST replay on divergence')
    parser.add_argument('--metacircuit', type=Path, default=REPO,
                        help='RTL checkout to simulate (default: this repository); golden inputs always come from here')
    args = parser.parse_args(argv)
    case = read(args.case) if args.case else {'scenario': read(args.scenario), 'seed': args.seed}
    seed = args.seed if args.seed is not None else case.get('seed')
    if type(seed) is not int or not 1 <= seed <= 2147483647:
        parser.error('a reproducible seed in 1..2147483647 is required')
    args.framescope = args.framescope.resolve()
    args.metacircuit = args.metacircuit.resolve()
    output = (args.out or GOLDEN / 'out/m4-lockstep' /
              datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%d-%H%M%S')).resolve()
    output.mkdir(parents=True, exist_ok=False)
    write(output / 'case.json', {**case, 'seed': seed})
    summary = {'ok': False, 'seed': seed, 'runtime': args.runtime,
               'scope': 'settled M1 canvas state; persistent frame stepping; no solver or transient qualification'}
    if args.metacircuit != REPO:
        summary['metacircuit'] = str(args.metacircuit)
    try:
        canonical, index, events = prepare(case['scenario'], output)
        # Import the chosen checkout, not an unrelated installed framescope.
        sys.path.insert(0, str(args.framescope / 'src'))
        os.environ['METACIRCUIT'] = str(args.metacircuit)
        from framescope import manifest, runtime
        from framescope.run import initialization_options
        from framescope.session import Session
        from verify_m4 import prepare_manifest
        config = prepare_manifest(args.framescope, output, False)
        m = manifest.load(config)
        initialization = initialization_options(m, seed)
        with Session(m, runtime.detect(args.runtime), lambda msg: print(msg, file=sys.stderr),
                     out=output / 'session', seed=seed) as session:
            if session.state.get('completed_frames') != 0:
                raise RuntimeError('lockstep requires a fresh cold session before frame 0')
            summary['build'] = session.br.to_json()
            summary['initialization'] = session.initialization
            if session.initialization != initialization:
                raise RuntimeError('session seeded-initialization provenance differs from request')
            summary.update(lockstep(session, canonical, index, events, output))
        from verify_m4 import functional_coverage
        summary['functional_coverage'] = functional_coverage(
            output / 'reference', {'checkpoints': [c for r in summary['comparisons'] for c in r['checkpoints']]},
            case.get('blocks'), rtl=output / 'rtl')
        if summary['first_divergence']:
            replay = replay_spec(args.framescope, config, output, seed, summary['first_divergence']['frame'],
                                 runtime=args.runtime, metacircuit=args.metacircuit)
            write(output / 'replay.json', replay)
            summary['replay'] = replay
            if args.replay_failure:
                summary['cold_replay_exit'] = command(replay['argv'], output / 'cold-replay.log', cwd=args.framescope)
                if summary['cold_replay_exit'] == 0:
                    summary['cold_replay'] = verify_cold_replay(output, summary['first_divergence'],
                                                              summary['initialization'])
    except Exception as error:
        summary.update(ok=False, error=f'{type(error).__name__}: {error}')
    write(output / 'summary.json', summary)
    print(json.dumps({'ok': summary['ok'], 'summary': str(output / 'summary.json')}, indent=2))
    return 0 if summary['ok'] else 1


if __name__ == '__main__':
    sys.exit(main())
