  // reg init = 1;
  // [INIT]: nothing, need cur        =>            provide nothing,     set addr = cur, state =>
  // depended on input (i, j) = incoming data's (i, j) [EDGE]: just got cur, need cur   => latch cur, provide RAM_out,     set addr = next
