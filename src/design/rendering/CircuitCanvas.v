  assign sprite_pixel = cell_enable ? DecodeTop(
      cell_type, cell_rotation, cell_offset_x, cell_offset_y
  ) : 1'b0;

  localparam integer ColorPos = 12'hFFF;  // #FFF
  localparam integer ColorNeg = 12'h222;  // #222
  localparam integer ColorNegHovering = 12'h280;  // #280

  wire [11:0] currentColorNeg;
  assign currentColorNeg = hovering ? ColorNegHovering : ColorNeg;

  localparam integer GridMarginWidth = 2;  // multiples of 2
  localparam integer GridColor = 12'h666;  // #666
  wire at_grid_edge;
  assign at_grid_edge =  cell_offset_x < GridMarginWidth / 2
                      || cell_offset_y < GridMarginWidth / 2
                      || cell_offset_x >= CellSize - GridMarginWidth / 2
                      || cell_offset_y >= CellSize - GridMarginWidth / 2;

  assign rgb = sprite_pixel ? ColorPos : (at_grid_edge ? GridColor : currentColorNeg);

  reg [1:0] status = 2'b00;

  always @(posedge clk_pixel) begin
    if (required_i_2 != latched_data_i || required_j_2 != latched_data_j) begin
      if (required_i_2 != incoming_data_i || required_j_2 != incoming_data_j) begin
        // [required cell index match either latched or incoming data indices]
        incoming_data_i <= required_i_2;
        incoming_data_j <= required_j_2;
        // to be decoded : empty data
        cell_data <= EmptyCellData;
        status <= 2'b01;

      end else begin
        // [required cell index match incoming data index]
        // set addr to next index
        incoming_data_i <= next_i;
        incoming_data_j <= next_j;
        // update latched data
        latched_data <= incoming_data;
        latched_data_i <= incoming_data_i;
        latched_data_j <= incoming_data_j;
        // to be decoded : incoming data
        cell_data <= incoming_data;
        status <= 2'b10;
      end
    end else begin
      // [required cell index match latched data index]
      // set addr to next index
      incoming_data_i <= next_i;
      incoming_data_j <= next_j;
      // to be decoded : latched data
      cell_data <= latched_data;
      status <= 2'b11;
    end
  end

  always @(posedge clk_pixel) begin   
      if (mouse_left_click) begin
          if (!is_dragging && mouse_in_canvas) begin
              // detect the click and assign dragging
              is_dragging   <= 1;
              click_start_x <= {1'b0, mouse_x_pos};
              click_start_y <= {1'b0, mouse_y_pos};
              grid_start_x  <= grid_pos_x;
              grid_start_y  <= grid_pos_y;
          end else if (is_dragging) begin
              //update the grid position and ensure the boundary condition
              grid_pos_x <= (next_grid_x > 0) ? 13'sd0 : 
                            (next_grid_x < min_grid_x) ? min_grid_x : next_grid_x[12:0];
                            
              grid_pos_y <= (next_grid_y > 0) ? 13'sd0 : 
                            (next_grid_y < min_grid_y) ? min_grid_y : next_grid_y[12:0];
          end
      end else begin
          is_dragging <= 0;
      end
  end

