  reg [3:0] cached_fg_color_idx = 4'hF;
  reg [3:0] cached_bg_color_idx = 4'h0;
  reg [11:0] cached_data_i = 12'b1111_1111_1111;
  reg [11:0] cached_data_j = 12'b1111_1111_1111;
